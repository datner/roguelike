//! Balance bench (docs/plans/balance.md): loads the builds and scenarios in `bench/`, runs each
//! build against each scenario through `game::balance` over many seeds, and writes the report. A
//! tool for changing content, not part of the game.

use std::fmt::Write as _;
use std::path::Path;

use game::Blueprints;
use game::balance::{self, Build, Run, Scenario, Summary};

/// The start of a fight: everything off recharge, every pool full.
pub const BURST: u64 = 1000;
/// A long fight: recharges, pools and ammunition come into it.
pub const SUSTAINED: u64 = 10_000;
/// Seeds `0..SEEDS` per run.
pub const SEEDS: u64 = 50;

/// Everything in `bench/`.
#[derive(Debug, Clone)]
pub struct Bench {
    /// In file-name order.
    pub builds: Vec<Build>,
    pub scenarios: Vec<Scenario>,
}

/// Reads `dir/builds/*.ron` and `dir/scenarios.ron`.
pub fn load(dir: &Path) -> Result<Bench, String> {
    let read = |path: &Path| {
        std::fs::read_to_string(path).map_err(|err| format!("{}: {err}", path.display()))
    };
    let mut paths: Vec<_> = std::fs::read_dir(dir.join("builds"))
        .map_err(|err| format!("{}: {err}", dir.join("builds").display()))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "ron"))
        .collect();
    paths.sort();
    let builds = paths
        .iter()
        .map(|path| ron::from_str(&read(path)?).map_err(|err| format!("{}: {err}", path.display())))
        .collect::<Result<_, String>>()?;
    let path = dir.join("scenarios.ron");
    let scenarios =
        ron::from_str(&read(&path)?).map_err(|err| format!("{}: {err}", path.display()))?;
    Ok(Bench { builds, scenarios })
}

/// One build against one scenario, both windows.
#[derive(Debug, Clone, PartialEq)]
pub struct Row {
    pub build: String,
    pub scenario: String,
    pub burst: Summary,
    pub sustained: Summary,
}

/// Every build against every scenario, over seeds `0..seeds`.
pub fn measure(blueprints: &Blueprints, bench: &Bench, seeds: u64) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    for scenario in &bench.scenarios {
        for build in &bench.builds {
            let window = |ticks| -> Result<Summary, String> {
                let runs = (0..seeds)
                    .map(|seed| balance::run(blueprints, build, scenario, ticks, seed))
                    .collect::<Result<Vec<Run>, String>>()?;
                Ok(balance::summarize(&runs))
            };
            rows.push(Row {
                build: build.name.clone(),
                scenario: scenario.name.clone(),
                burst: window(BURST)?,
                sustained: window(SUSTAINED)?,
            });
        }
    }
    Ok(rows)
}

/// The report, as markdown: the builds, then one table per scenario.
pub fn report(bench: &Bench, rows: &[Row], seeds: u64) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Balance report\n");
    let _ = writeln!(
        out,
        "Generated by `scripts/balance.sh`; do not edit. {seeds} seeds per cell. Damage per turn \
         (100 ticks) against training dolls: mean (10th–90th percentile). Burst is the first \
         {BURST} ticks, sustained the first {SUSTAINED}. Landed and grazed are shares of every \
         blow, over the sustained window.\n"
    );
    let _ = writeln!(out, "## Builds\n");
    for build in &bench.builds {
        let _ = writeln!(out, "- **{}**: {}", build.name, build.note);
    }
    for scenario in &bench.scenarios {
        let _ = writeln!(out, "\n## {}\n", scenario.name);
        let _ = writeln!(out, "| build | burst | sustained | landed | grazed |");
        let _ = writeln!(out, "|---|---|---|---|---|");
        for row in rows.iter().filter(|row| row.scenario == scenario.name) {
            let _ = writeln!(
                out,
                "| {} | {} | {} | {:.0}% | {:.0}% |",
                row.build,
                spread(&row.burst),
                spread(&row.sustained),
                row.sustained.landed * 100.0,
                row.sustained.grazed * 100.0,
            );
        }
    }
    if let Some(first) = bench.scenarios.first() {
        spending(&mut out, rows, first);
    }
    out
}

/// What each build spends over the sustained window of `scenario`, and
/// when it runs dry. Running dry inside the burst window is flagged: such a
/// build can't keep up even a short fight.
fn spending(out: &mut String, rows: &[Row], scenario: &Scenario) {
    let _ = writeln!(out, "\n## What it spends\n");
    let _ = writeln!(
        out,
        "Per run of the sustained window against \"{}\". Runs dry: the share of runs that could no \
         longer pay for the cheapest thing they had paid for (or held no arrows), and when on \
         average.\n",
        scenario.name
    );
    let _ = writeln!(
        out,
        "| build | mana | stamina | arrows (broken) | own health | runs dry |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for row in rows.iter().filter(|row| row.scenario == scenario.name) {
        let s = &row.sustained;
        let dry: Vec<String> = [
            ("mana", s.mana),
            ("stamina", s.stamina),
            ("arrows", s.arrows),
        ]
        .into_iter()
        .filter_map(|(name, use_)| {
            let at = use_.dry_at?;
            let flag = if at < BURST as f64 && use_.dry >= 0.5 {
                " **in burst**"
            } else {
                ""
            };
            Some(format!(
                "{name} {:.0}% at {at:.0} ticks{flag}",
                use_.dry * 100.0
            ))
        })
        .collect();
        let _ = writeln!(
            out,
            "| {} | {:.1} | {:.1} | {:.1} ({:.1}) | {:.1} | {} |",
            row.build,
            s.mana.spent,
            s.stamina.spent,
            s.arrows.spent,
            s.arrows_broken,
            s.health,
            if dry.is_empty() {
                "—".to_string()
            } else {
                dry.join("; ")
            },
        );
    }
}

fn spread(summary: &Summary) -> String {
    format!(
        "{:.2} ({:.2}–{:.2})",
        summary.mean, summary.low, summary.high
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dir() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).to_path_buf()
    }

    fn data() -> Blueprints {
        Blueprints::load(&dir().join("../data")).unwrap()
    }

    #[test]
    fn every_build_and_scenario_loads_and_runs() {
        let bench = load(&dir()).unwrap();
        assert!(!bench.builds.is_empty() && !bench.scenarios.is_empty());
        let rows = measure(&data(), &bench, 1).unwrap();
        assert_eq!(rows.len(), bench.builds.len() * bench.scenarios.len());
    }
}

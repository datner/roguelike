#!/usr/bin/env bash
# Writes docs/MAP.md (or the path given as $1): per .rs file in game/ and
# term/, its line count, first `//!` line, and every pub item's signature.
# Lets a session orient without reading whole files. Line-based on purpose
# (no parser), so it relies on rustfmt layout; check.sh keeps it fresh.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C

out=${1:-docs/MAP.md}

item_re='^( *)pub(\([a-z]+\))? ((const|async|unsafe|extern "C") )*(fn|struct|enum|trait|type|const|static) '
tests_re='^(pub(\([a-z]+\))? )?mod tests'
mod_re='^(pub(\([a-z]+\))? )?mod [a-z_]+ \{'

# Joins rustfmt-wrapped signature lines back into one.
join() {
  local acc=$1 line=$2
  if [[ $acc == *[\(\<\[] ]]; then
    printf '%s' "$acc$line"
  elif [[ $line == [\)\>\]]* ]]; then
    printf '%s' "${acc%,}$line"
  else
    printf '%s' "$acc $line"
  fi
}

# Trims a joined signature to everything before its body or value.
trim_sig() {
  local sig=$1
  if [[ $sig =~ ^(pub(\([a-z]+\))? )?(const|static)\  && $sig == *' = ['* ]]; then
    sig=${sig%% = *}
  fi
  sig=${sig%%\{*}
  sig=${sig%;}
  sig=${sig%"${sig##*[![:space:]]}"}
  printf '%s' "${sig%% where}"
}

map_file() {
  local f=$1 lines summary impl='' impl_shown='' sig='' indent='' line
  lines=$(wc -l <"$f")
  summary=$(grep -m1 '^//!' "$f" || true)
  summary=${summary#//!}
  summary=${summary# }
  printf '\n## %s (%d) — %s\n' "$f" "$lines" "${summary:-(no module doc)}"

  while IFS= read -r line || [[ -n $line ]]; do
    [[ $line =~ $tests_re ]] && break
    if [[ -n $sig ]]; then
      line=${line#"${line%%[![:space:]]*}"}
      sig=$(join "$sig" "$line")
      if [[ $line == *'{'* || $line == *';' ]]; then
        printf -- '%s- `%s`\n' "$indent" "$(trim_sig "$sig")"
        sig=''
      fi
      continue
    fi
    if [[ $line == 'impl'* || $line =~ $mod_re ]]; then
      impl=$(trim_sig "$line")
      impl_shown=''
      continue
    fi
    [[ $line =~ $item_re ]] || continue
    indent=''
    if [[ -n ${BASH_REMATCH[1]} ]]; then
      indent='  '
      if [[ -n $impl && -z $impl_shown ]]; then
        printf -- '- `%s`\n' "$impl"
        impl_shown=1
      fi
    fi
    line=${line#"${line%%[![:space:]]*}"}
    if [[ $line == *'{'* || $line == *';' ]]; then
      printf -- '%s- `%s`\n' "$indent" "$(trim_sig "$line")"
    else
      sig=$line
    fi
  done <"$f"
}

{
  echo '# Code map'
  echo
  echo 'Generated by `scripts/map.sh`; do not edit. Per file: path (line count) — first `//!` line, then pub signatures (nested = inside the `impl` or `mod` above). Test modules are skipped.'
  fd -e rs . game term | sort | while IFS= read -r f; do
    map_file "$f"
  done
} >"$out"

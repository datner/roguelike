#!/usr/bin/env bash
# Two modes, both line-based on purpose (no parser, relies on rustfmt layout):
#   scripts/map.sh [OUT]          writes the module index (default docs/MAP.md):
#                                 per .rs file in each crate, its size
#                                 rounded to 100 lines and its first `//!`
#                                 paragraph. Loaded into every session, so it
#                                 grows with modules, not items; check.sh keeps
#                                 it fresh.
#   scripts/map.sh --sigs PATH... prints every pub item's signature in the given
#                                 files or directories, for the modules a task
#                                 touches.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C

out=${1:-docs/MAP.md}

item_re='^( *)pub(\([a-z]+\))? ((const|async|unsafe|extern "C") )*(fn|struct|enum|trait|type|const|static) '
tests_re='^(pub(\([a-z]+\))? )?mod tests'
mod_re='^(pub(\([a-z]+\))? )?mod [a-z_]+ \{'

# Joins rustfmt-wrapped signature lines back into one.
join() {
  local acc=$1 line=$2
  if [[ $acc == *[\(\<\[] ]]; then
    printf '%s' "$acc$line"
  elif [[ $line == [\)\>\]]* ]]; then
    printf '%s' "${acc%,}$line"
  else
    printf '%s' "$acc $line"
  fi
}

# Trims a joined signature to everything before its body or value.
trim_sig() {
  local sig=$1
  if [[ $sig =~ ^(pub(\([a-z]+\))? )?(const|static)\  && $sig == *' = ['* ]]; then
    sig=${sig%% = *}
  fi
  sig=${sig%%\{*}
  sig=${sig%;}
  sig=${sig%"${sig##*[![:space:]]}"}
  printf '%s' "${sig%% where}"
}

# The module doc's first paragraph, joined onto one line.
summary() {
  local line text=''
  while IFS= read -r line || [[ -n $line ]]; do
    [[ $line == '//!'* ]] || break
    line=${line#//!}
    line=${line# }
    [[ -z $line ]] && break
    text=${text:+$text }$line
  done <"$1"
  printf '%s' "${text:-(no module doc)}"
}

# One index line. Size is rounded to 100 lines (at least 100) so ordinary
# edits don't make the index stale; it only says whether a file is big.
index_line() {
  local f=$1 lines
  lines=$(wc -l <"$f")
  lines=$(((lines + 50) / 100 * 100))
  ((lines < 100)) && lines=100
  printf -- '- `%s` (~%d) — %s\n' "$f" "$lines" "$(summary "$f")"
}

sigs_file() {
  local f=$1 impl='' impl_shown='' sig='' indent='' line
  printf '\n## %s\n' "$f"

  while IFS= read -r line || [[ -n $line ]]; do
    [[ $line =~ $tests_re ]] && break
    if [[ -n $sig ]]; then
      line=${line#"${line%%[![:space:]]*}"}
      sig=$(join "$sig" "$line")
      if [[ $line == *'{'* || $line == *';' ]]; then
        printf -- '%s- `%s`\n' "$indent" "$(trim_sig "$sig")"
        sig=''
      fi
      continue
    fi
    if [[ $line == 'impl'* || $line =~ $mod_re ]]; then
      impl=$(trim_sig "$line")
      impl_shown=''
      continue
    fi
    [[ $line =~ $item_re ]] || continue
    indent=''
    if [[ -n ${BASH_REMATCH[1]} ]]; then
      indent='  '
      if [[ -n $impl && -z $impl_shown ]]; then
        printf -- '- `%s`\n' "$impl"
        impl_shown=1
      fi
    fi
    line=${line#"${line%%[![:space:]]*}"}
    if [[ $line == *'{'* || $line == *';' ]]; then
      printf -- '%s- `%s`\n' "$indent" "$(trim_sig "$line")"
    else
      sig=$line
    fi
  done <"$f"
}

if [[ ${1:-} == --sigs ]]; then
  shift
  (($#)) || { echo 'usage: scripts/map.sh --sigs PATH...' >&2; exit 2; }
  for path in "$@"; do
    if [[ -d $path ]]; then fd -e rs . "$path" | sort; else echo "$path"; fi
  done | while IFS= read -r f; do
    sigs_file "$f"
  done
  exit
fi

{
  echo '# Code map'
  echo
  echo 'Generated by `scripts/map.sh`; do not edit. One line per module: path (size, rounded to 100 lines) — its `//!` summary. Signatures: `scripts/map.sh --sigs <file or dir>...` (nested = inside the `impl` or `mod` above; test modules skipped).'
  for crate in game front term gui; do
    printf '\n## %s\n\n' "$crate"
    fd -e rs . "$crate" | sort | while IFS= read -r f; do
      index_line "$f"
    done
  done
} >"$out"
